fn glyph(ch: char) -> Option<&'static [u8; 7]> {
    let upper = ch.to_ascii_uppercase();
    let fold_upper = ch.is_ascii_alphabetic();
    FONT.iter()
        .find(|(c, _)| *c == ch || (fold_upper && *c == upper))
        .map(|(_, rows)| rows)
}

/// Measures `content` rendered at `font_size`.
pub fn measure(content: &str, font_size: f64) -> (f64, f64) {
    let scale = (font_size / GLYPH_H as f64).max(0.2);
    let width = content.chars().count() as f64 * ADVANCE * scale;
    (width.max(1.0), (font_size * 1.2).max(1.0))
}

/// Renders `content` as premultiplied RGBA pixels, top-left origin.
pub fn render_text(content: &str, font_size: f64, color: [u8; 4]) -> Bitmap {
    let scale = (font_size / GLYPH_H as f64).max(0.2);
    let (width, height) = measure(content, font_size);
    let mut out = Bitmap::new(width.ceil() as usize, height.ceil() as usize);
    let mut pen_x = 0.0f64;
    for ch in content.chars() {
        if let Some(rows) = glyph(ch) {
            for (row, bits) in rows.iter().enumerate() {
                for col in 0..GLYPH_W {
                    if bits & (1 << (GLYPH_W - 1 - col)) == 0 {
                        continue;
                    }
                    // Fill the scaled cell.
                    let x0 = (pen_x + col as f64 * scale).floor() as usize;
                    let x1 = ((pen_x + (col + 1) as f64 * scale).ceil() as usize).max(x0 + 1);
                    let y0 = (row as f64 * scale).floor() as usize;
                    let y1 = (((row + 1) as f64 * scale).ceil() as usize).max(y0 + 1);
                    for y in y0..y1.min(out.height) {
                        for x in x0..x1.min(out.width) {
                            out.set_pixel(x, y, color);
                        }
                    }
                }
            }
        }
        pen_x += ADVANCE * scale;
    }
    out
}
